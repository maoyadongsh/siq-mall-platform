"""统一错误码（架构文档 §5.4）。5 位十进制，模块位固定，业务代码禁止写裸数字。"""


class ErrorCode:
    # 通用 / 框架
    SUCCESS = 0
    INVALID_PARAM = 10001
    UNAUTHENTICATED = 10002
    PERMISSION_DENIED = 10003
    NOT_FOUND = 10004
    THROTTLED = 10005
    SERVER_ERROR = 10006
    METHOD_NOT_ALLOWED = 10007
    VERSION_CONFLICT = 10008
    IDEMPOTENCY_CONFLICT = 10010

    # 用户 / 鉴权
    LOGIN_FAILED = 20001
    CAPTCHA_INVALID = 20002
    ACCOUNT_EXISTS = 20003
    TOKEN_INVALID = 20004
    PASSWORD_TOO_WEAK = 20005
    VERIFICATION_UNAVAILABLE = 20006
    ADDRESS_LIMIT_EXCEEDED = 20007
    PHONE_CONFLICT = 20008

    # 商品
    PRODUCT_UNAVAILABLE = 30001
    STOCK_NOT_ENOUGH = 30002
    CATEGORY_NOT_FOUND = 30003

    # 购物车 / 订单
    CART_LIMIT = 40008
    CART_EMPTY = 40001
    ORDER_NOT_FOUND = 40002
    ORDER_STATUS_INVALID = 40003
    DUPLICATE_SUBMIT = 40004

    # 支付
    PAYMENT_NOT_FOUND = 50001
    PAYMENT_STATUS_INVALID = 50002
    PAYMENT_AMOUNT_MISMATCH = 50003

    # 优惠券
    COUPON_NOT_CLAIMABLE = 60001
    COUPON_NOT_USABLE = 60002
    COUPON_USED = 60003

    # 评价
    ORDER_NOT_COMPLETED = 70001
    REVIEW_DUPLICATED = 70002

    # 通知
    NOTICE_NOT_FOUND = 80001

    # CMS / 客服
    CONTENT_OFFLINE = 90001
    CHAT_SESSION_NOT_FOUND = 90002
